const ExcelJS = require('exceljs');
const fs = require('fs');
const path = require('path');

const DOWNLOAD_DIR = path.join(__dirname, '../../test-downloads');

const files = [
  'Farmer_Dashboard_Report_7days.xlsx',
  'Admin_Dashboard_Report_today.xlsx',
  'Admin_Dashboard_Report_all.xlsx'
];

async function verifyExcelFile(filename) {
  const fp = path.join(DOWNLOAD_DIR, filename);
  const wb = await new ExcelJS.Workbook().xlsx.readFile(fp);
  const ws = wb.worksheets[0];
  
  const results = {
    filename,
    logo: {},
    generatedBy: {},
    sections: [],
    formatting: {},
    errors: []
  };

  // 1. Verify Logo
  const images = ws.getImages();
  if (images.length > 0) {
    const img = images[0];
    results.logo = {
      present: true,
      position: {
        col: img.range.tl.col,
        row: img.range.tl.row,
        colChar: String.fromCharCode(65 + img.range.tl.col)
      },
      size: {
        width: img.range.ext.width,
        height: img.range.ext.height
      },
      aspectRatio: (img.range.ext.width / img.range.ext.height).toFixed(2)
    };
    
    // Check if logo is at B1 (col=1, row=0)
    if (img.range.tl.col !== 1 || img.range.tl.row !== 0) {
      results.errors.push(`Logo not at B1: found at column ${img.range.tl.col}, row ${img.range.tl.row}`);
    }
    
    // Check aspect ratio (should be 1.0 for square logo)
    const ratio = img.range.ext.width / img.range.ext.height;
    if (Math.abs(ratio - 1.0) > 0.1) {
      results.errors.push(`Logo aspect ratio distorted: ${ratio.toFixed(2)} (expected ~1.0)`);
    }
  } else {
    results.logo.present = false;
    results.errors.push('No logo found in worksheet');
  }

  // 2. Verify Generated By section
  // Look for "Generated By" header and extract values
  let generatedByRow = 0;
  for (let row = 1; row <= 20; row++) {
    const cell = ws.getCell(row, 1);
    if (cell.value && cell.value.toString().includes('Generated By')) {
      generatedByRow = row;
      break;
    }
  }
  
  if (generatedByRow > 0) {
    results.generatedBy.headerRow = generatedByRow;
    results.generatedBy.name = ws.getCell(generatedByRow + 1, 2).value || 'NOT FOUND';
    results.generatedBy.email = ws.getCell(generatedByRow + 2, 2).value || 'NOT FOUND';
    results.generatedBy.phone = ws.getCell(generatedByRow + 3, 2).value || 'NOT FOUND';
    results.generatedBy.role = ws.getCell(generatedByRow + 4, 2).value || 'NOT FOUND';
    
    if (results.generatedBy.name === 'NOT FOUND') results.errors.push('Generated By: Name not found');
    if (results.generatedBy.email === 'NOT FOUND') results.errors.push('Generated By: Email not found');
    if (results.generatedBy.phone === 'NOT FOUND') results.errors.push('Generated By: Phone not found');
    if (results.generatedBy.role === 'NOT FOUND') results.errors.push('Generated By: Role not found');
  } else {
    results.errors.push('Generated By section not found');
  }

  // 3. Verify Report Information section
  let reportInfoRow = 0;
  for (let row = 1; row <= 20; row++) {
    const cell = ws.getCell(row, 1);
    if (cell.value && cell.value.toString().includes('Report Information')) {
      reportInfoRow = row;
      break;
    }
  }
  
  if (reportInfoRow > 0) {
    results.generatedBy.period = ws.getCell(reportInfoRow + 1, 2).value || 'NOT FOUND';
    results.generatedBy.dateTime = ws.getCell(reportInfoRow + 2, 2).value || 'NOT FOUND';
  } else {
    results.errors.push('Report Information section not found');
  }

  // 4. Identify all sections
  const sectionHeaders = [];
  for (let row = 1; row <= 100; row++) {
    const cell = ws.getCell(row, 1);
    if (cell.value && typeof cell.value === 'string') {
      const val = cell.value.trim();
      // Look for section headers (bold, larger font, or specific patterns)
      if (val.includes('Report') || val.includes('By') || val.includes('Key Performance') || 
          val.includes('Sales') || val.includes('Orders') || val.includes('Products') ||
          val.includes('Recent') || val.includes('Top') || val.includes('Farmers') ||
          val.includes('Customers') || val.includes('Revenue') || val.includes('Status')) {
        const font = cell.font || {};
        if (font.bold || font.size >= 12) {
          sectionHeaders.push({ row, value: val });
        }
      }
    }
  }
  results.sections = sectionHeaders;

  // 5. Verify formatting
  results.formatting.row1Height = ws.getRow(1).height;
  results.formatting.columnWidths = [];
  for (let col = 1; col <= 6; col++) {
    results.formatting.columnWidths.push(ws.getColumn(col).width);
  }

  // Check for common formatting issues
  if (results.formatting.row1Height < 50) {
    results.errors.push(`Row 1 height too small for logo: ${results.formatting.row1Height}`);
  }

  return results;
}

async function main() {
  console.log('=== FINAL DASHBOARD EXPORT VALIDATION REPORT ===\n');
  
  const allResults = [];
  
  for (const file of files) {
    try {
      const results = await verifyExcelFile(file);
      allResults.push(results);
      
      console.log(`\n═══════════════════════════════════════════════════════════════`);
      console.log(`FILE: ${results.filename}`);
      console.log(`═══════════════════════════════════════════════════════════════`);
      
      // Logo Verification
      console.log('\n1. LOGO VERIFICATION');
      if (results.logo.present) {
        console.log(`   ✓ Logo Present`);
        console.log(`   Position: ${results.logo.position.colChar}${results.logo.position.row + 1}`);
        console.log(`   Size: ${results.logo.size.width}x${results.logo.size.height}`);
        console.log(`   Aspect Ratio: ${results.logo.aspectRatio}`);
        if (results.logo.position.col === 1 && results.logo.position.row === 0) {
          console.log(`   ✓ Logo at B1 (correct)`);
        } else {
          console.log(`   ✗ Logo NOT at B1 (found at ${results.logo.position.colChar}${results.logo.position.row + 1})`);
        }
      } else {
        console.log(`   ✗ Logo NOT FOUND`);
      }
      
      // Generated By Verification
      console.log('\n2. GENERATED BY SECTION');
      if (results.generatedBy.headerRow > 0) {
        console.log(`   ✓ Section found at row ${results.generatedBy.headerRow}`);
        console.log(`   Name: ${results.generatedBy.name}`);
        console.log(`   Email: ${results.generatedBy.email}`);
        console.log(`   Phone: ${results.generatedBy.phone}`);
        console.log(`   Role: ${results.generatedBy.role}`);
        console.log(`   Period: ${results.generatedBy.period}`);
        console.log(`   DateTime: ${results.generatedBy.dateTime}`);
      } else {
        console.log(`   ✗ Generated By section NOT FOUND`);
      }
      
      // Sections
      console.log('\n3. SECTIONS FOUND');
      results.sections.forEach(section => {
        console.log(`   - Row ${section.row}: ${section.value}`);
      });
      
      // Formatting
      console.log('\n4. FORMATTING');
      console.log(`   Row 1 Height: ${results.formatting.row1Height}`);
      console.log(`   Column Widths: ${results.formatting.columnWidths.map(w => w?.toFixed(1) || 'auto').join(', ')}`);
      
      // Errors
      if (results.errors.length > 0) {
        console.log('\n5. ERRORS');
        results.errors.forEach(err => {
          console.log(`   ✗ ${err}`);
        });
      } else {
        console.log('\n5. ERRORS: None');
      }
      
    } catch (e) {
      console.log(`\n═══════════════════════════════════════════════════════════════`);
      console.log(`FILE: ${file}`);
      console.log(`═══════════════════════════════════════════════════════════════`);
      console.log(`✗ CORRUPTED: ${e.message}`);
    }
  }
  
  // Summary
  console.log('\n\n═══════════════════════════════════════════════════════════════');
  console.log('SUMMARY');
  console.log('═══════════════════════════════════════════════════════════════');
  
  const totalErrors = allResults.reduce((sum, r) => sum + r.errors.length, 0);
  const filesWithLogo = allResults.filter(r => r.logo.present).length;
  const filesWithGeneratedBy = allResults.filter(r => r.generatedBy.headerRow > 0).length;
  
  console.log(`Files Verified: ${allResults.length}`);
  console.log(`Files with Logo: ${filesWithLogo}/${allResults.length}`);
  console.log(`Files with Generated By: ${filesWithGeneratedBy}/${allResults.length}`);
  console.log(`Total Errors: ${totalErrors}`);
  
  if (totalErrors === 0 && filesWithLogo === allResults.length && filesWithGeneratedBy === allResults.length) {
    console.log('\n✓ ALL CHECKS PASSED');
  } else {
    console.log('\n✗ SOME CHECKS FAILED');
  }
}

main().catch(console.error);
